/// Drop-in replacement for Material [Icon] using HugeIcons glyphs.
///
/// Default [strokeWidth] is tuned so stroke-rounded icons stay crisp on glass UI.
/// Directional arrows (back / forward) auto-mirror in RTL like Material icons.
class AppIcon extends StatelessWidget {
  const AppIcon(
    this.icon, {
    super.key,
    this.size = 24,
    this.color,
    this.strokeWidth = 1.65,
    this.matchTextDirection,
  });

  final AppIconData icon;
  final double? size;
  final Color? color;
  final double? strokeWidth;

  /// When null, directional arrows auto-match [Directionality].
  final bool? matchTextDirection;

  static bool _isDirectional(AppIconData icon) {
    return identical(icon, AppIcons.arrowBack) ||
        identical(icon, AppIcons.arrowBackIosNew) ||
        identical(icon, AppIcons.arrowForward) ||
        identical(icon, AppIcons.arrowForwardIos);
  }

  @override
  Widget build(BuildContext context) {
    Widget child = HugeIcon(
      icon: icon,
      size: size,
      color: color,
      strokeWidth: strokeWidth,
    );

    final shouldMatch = matchTextDirection ?? _isDirectional(icon);
    if (shouldMatch && Directionality.of(context) == TextDirection.rtl) {
      child = Transform.flip(flipX: true, child: child);
    }

    return child;
  }
}
